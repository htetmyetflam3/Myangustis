#!/usr/bin/env node
// CLI.js — the only entry point. Two commands, nothing else:
//
//   node CLI.js buildstart   build the trees into ./tree (4 map + 3 graph modules)
//   node CLI.js obfuscator   encrypt master.json -> master.json.enc, emit the
//                            external key (master.key.txt) and the loader secure.js
//
// Loads .env next to this file first. The master key is a mandatory
// dependency for sealing/loading: MASTER_JSON_KEY from the process/.env,
// then .cache/master.key.txt, then the tracked master.key.txt in git. All
// paths are anchored here; the tree output is hardcoded to ./tree beside
// this CLI. Node stdlib only.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const MASTER = path.join(HERE, "master.json");
const TREE_DIR = path.join(HERE, "tree");
const ENC_PATH = path.join(HERE, "master.json.enc");
const KEY_PATH = path.join(HERE, "master.key.txt");
const CACHE_KEY_PATH = path.join(HERE, ".cache", "master.key.txt");
const SECURE_PATH = path.join(HERE, "secure.js");

const MAGIC = "MGR1";
const IV_BYTES = 12;
const TAG_BYTES = 16;
const KEY_BYTES = 32;

// Minimal .env loader: KEY=VALUE lines next to this CLI, if present.
// Real process env wins; an empty process value is filled from .env.
function loadEnv() {
  const envPath = path.join(HERE, ".env");
  if (!fs.existsSync(envPath)) return false;
  for (const line of fs.readFileSync(envPath, "utf8").split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq === -1) continue;
    const k = t.slice(0, eq).trim();
    if (process.env[k] === undefined || process.env[k] === "") {
      process.env[k] = t.slice(eq + 1).trim();
    }
  }
  return true;
}

function keyFromHex(hex, label) {
  const text = String(hex || "").trim();
  if (!/^[0-9a-f]{64}$/i.test(text)) {
    throw new Error(`${label} must hold a 32-byte hex key (64 chars)`);
  }
  return { key: Buffer.from(text, "hex"), keyHex: text.toLowerCase(), source: label };
}

// Mandatory master-key resolution for rebuild/seal. Never mint a fresh key
// here: a later agent must be able to retrieve the exact key from .env, the
// .cache fallback, or the tracked master.key.txt in git.
function loadMasterKey() {
  const fromEnv = (process.env.MASTER_JSON_KEY || "").trim();
  if (fromEnv) return keyFromHex(fromEnv, "MASTER_JSON_KEY (.env/process env)");
  for (const [label, file] of [
    [".cache/master.key.txt", CACHE_KEY_PATH],
    ["master.key.txt (tracked)", KEY_PATH],
  ]) {
    if (fs.existsSync(file)) return keyFromHex(fs.readFileSync(file, "utf8"), label);
  }
  throw new Error(
    "MASTER_JSON_KEY is mandatory: set it in .env or place .cache/master.key.txt " +
      "or the tracked master.key.txt beside CLI.js",
  );
}

// ── command 1: tree build ────────────────────────────────────────────────
async function buildStart() {
  fs.mkdirSync(TREE_DIR, { recursive: true });
  if (fs.existsSync(ENC_PATH)) {
    const { source } = loadMasterKey();
    console.log(`[buildstart] master key dependency ok (${source})`);
  }
  const { runBuild, runBuildPos } = await import("./graph/build.js");
  // Same two-phase build the engine runs: syllable trees, then the POS tree
  // keyed on the minted ids (refArray threaded in memory).
  const { refArray } = await runBuild();
  await runBuildPos(TREE_DIR, refArray);
  console.log(`[buildstart] trees written to ${TREE_DIR}`);
  for (const f of fs.readdirSync(TREE_DIR)) console.log("  -", f);
}

// ── command 2: encrypt master.json + external key + loader ───────────────
function seal(key, plain) {
  const iv = crypto.randomBytes(IV_BYTES);
  const cipher = crypto.createCipheriv("aes-256-gcm", key, iv);
  const ct = Buffer.concat([cipher.update(plain), cipher.final()]);
  return Buffer.concat([Buffer.from(MAGIC, "ascii"), iv, cipher.getAuthTag(), ct]);
}

// The loader. The key is NOT embedded and NOT optional: secure.js resolves
// MASTER_JSON_KEY from .env/process env, then .cache/master.key.txt, then
// the tracked master.key.txt. The obfuscator reuses that mandatory key; it
// never mints an unretrievable replacement.
const SECURE_SOURCE = `// secure.js — GENERATED by CLI.js obfuscator. Do not edit by hand.
// AES-256-GCM loader for master.json.enc. The key lives in master.key.txt
// beside this file (external sidecar), never inside the loader.
// Container: [4-byte magic "MGR1"][12-byte IV][16-byte auth tag][ciphertext]
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const KEY_FILE = path.join(HERE, "master.key.txt");
const CACHE_KEY_FILE = path.join(HERE, ".cache", "master.key.txt");
const MAGIC = "MGR1";
const IV_BYTES = 12;
const TAG_BYTES = 16;

function keyFromHex(hex, label) {
  const text = String(hex || "").trim();
  if (!/^[0-9a-f]{64}$/i.test(text)) {
    throw new Error(label + " must hold a 32-byte hex key (64 chars)");
  }
  return Buffer.from(text, "hex");
}

function keyFromEnvFile() {
  const envPath = path.join(HERE, ".env");
  if (!fs.existsSync(envPath)) return "";
  for (const line of fs.readFileSync(envPath, "utf8").split(/\\r?\\n/)) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq === -1) continue;
    if (t.slice(0, eq).trim() === "MASTER_JSON_KEY") return t.slice(eq + 1).trim();
  }
  return "";
}

function loadKey() {
  // Mandatory key resolution, in order: process env, .env beside this
  // loader, .cache/master.key.txt, then the tracked master.key.txt in git.
  // The key is never embedded in this file and is never optional.
  const fromEnv = (process.env.MASTER_JSON_KEY || "").trim() || keyFromEnvFile();
  if (fromEnv) return keyFromHex(fromEnv, "MASTER_JSON_KEY (.env/process env)");
  for (const [label, file] of [
    [".cache/master.key.txt", CACHE_KEY_FILE],
    ["master.key.txt (tracked)", KEY_FILE],
  ]) {
    if (fs.existsSync(file)) return keyFromHex(fs.readFileSync(file, "utf8"), label);
  }
  throw new Error(
    "MASTER_JSON_KEY is mandatory: set it in .env or place .cache/master.key.txt " +
      "or the tracked master.key.txt beside secure.js",
  );
}

function decrypt(file) {
  const container = fs.readFileSync(file);
  if (
    container.length < 4 + IV_BYTES + TAG_BYTES ||
    container.subarray(0, 4).toString("ascii") !== MAGIC
  ) {
    throw new Error("invalid .enc container (expected the MGR1 layout): " + file);
  }
  const iv = container.subarray(4, 4 + IV_BYTES);
  const tag = container.subarray(4 + IV_BYTES, 4 + IV_BYTES + TAG_BYTES);
  const ciphertext = container.subarray(4 + IV_BYTES + TAG_BYTES);
  const decipher = crypto.createDecipheriv("aes-256-gcm", loadKey(), iv);
  decipher.setAuthTag(tag);
  return Buffer.concat([decipher.update(ciphertext), decipher.final()]).toString("utf8");
}

export function readSecureText(file) {
  const enc = file.endsWith(".enc") ? file : file + ".enc";
  if (!fs.existsSync(enc)) {
    throw new Error(
      "sealed file not found: " + enc + " (run node CLI.js obfuscator; the master key is mandatory)",
    );
  }
  return decrypt(enc);
}

export function readSecureJson(file) {
  return JSON.parse(readSecureText(file));
}
`;

function obfuscator() {
  if (!fs.existsSync(MASTER)) throw new Error(`master.json not found: ${MASTER}`);
  const data = fs.readFileSync(MASTER);
  JSON.parse(data.toString("utf8")); // fail fast on a non-JSON source

  const { key, keyHex, source } = loadMasterKey();
  if (key.length !== KEY_BYTES) throw new Error("master key must be exactly 32 bytes");
  // Keep the tracked sidecar in sync with the key actually used, so a later
  // agent can always retrieve it from git and test the loader.
  const trackedKey = fs.existsSync(KEY_PATH) ? fs.readFileSync(KEY_PATH, "utf8").trim().toLowerCase() : "";
  if (trackedKey !== keyHex) fs.writeFileSync(KEY_PATH, keyHex + "\n", "utf8");
  fs.writeFileSync(ENC_PATH, seal(key, data));
  fs.writeFileSync(SECURE_PATH, SECURE_SOURCE, "utf8");

  console.log("[obfuscator] AES-256-GCM (MGR1) outputs:");
  console.log("  key    ->", path.relative(HERE, KEY_PATH), `(${KEY_BYTES}-byte hex, tracked; source: ${source})`);
  console.log("  sealed ->", path.relative(HERE, ENC_PATH), `${(ENC_PATH && fs.statSync(ENC_PATH).size)} bytes`);
  console.log("  loader ->", path.relative(HERE, SECURE_PATH), "(requires the external key)");
}

// ── dispatch ─────────────────────────────────────────────────────────────
loadEnv();
const command = process.argv[2];
if (command === "buildstart") {
  buildStart().catch((err) => {
    console.error(err);
    process.exit(1);
  });
} else if (command === "obfuscator") {
  try {
    obfuscator();
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
} else {
  console.error("usage:\n  node CLI.js buildstart\n  node CLI.js obfuscator");
  process.exit(2);
}
